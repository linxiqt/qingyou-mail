import test from "node:test";
import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import {
  mkdtemp,
  readFile,
  readdir,
  rm,
  stat,
  writeFile,
} from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import {
  ensureDomainKeys,
  generateDomainKey,
  rspamdKeyPath,
} from "../src/domain-keys.js";
import { loadConfig } from "../src/config.js";

const fixture = generateDomainKey();

function database() {
  const db = new DatabaseSync(":memory:");
  db.exec(`CREATE TABLE domains(id INTEGER PRIMARY KEY,name TEXT NOT NULL);
    CREATE TABLE domain_keys(domain_id INTEGER PRIMARY KEY,selector TEXT NOT NULL,private_key TEXT NOT NULL,public_key TEXT NOT NULL);
    INSERT INTO domains(id,name) VALUES(1,'sample.example');`);
  return db;
}

test("Rspamd configuration confines scanning to a loopback endpoint and validates selector", () => {
  assert.equal(loadConfig({}).dkimBackend, "node");
  const config = loadConfig({ DKIM_BACKEND: "rspamd" });
  assert.equal(config.rspamdSelector, "rspamd");
  assert.equal(config.rspamdUrl, "http://127.0.0.1:11333/checkv2");
  assert.equal(config.rspamdTimeoutMs, 10000);
  assert.equal(
    loadConfig({ RSPAMD_URL: "http://[::1]:11333/checkv2" }).rspamdUrl,
    "http://[::1]:11333/checkv2",
  );
  for (const url of [
    "http://localhost:11333/checkv2",
    "http://192.0.2.1:11333/checkv2",
    "http://127.0.0.1:11333/checkv2?x=1",
    "http://127.0.0.1:11333/checkv2#fragment",
    "http://user:password@127.0.0.1:11333/checkv2",
    "http://127.0.0.1:11333/other",
  ])
    assert.throws(() => loadConfig({ RSPAMD_URL: url }), /RSPAMD_URL/);
  for (const selector of [
    "../key",
    "A",
    "has.dot",
    "-start",
    "end-",
    "a".repeat(64),
  ])
    assert.throws(
      () => loadConfig({ RSPAMD_SELECTOR: selector }),
      /RSPAMD_SELECTOR/,
    );
  assert.throws(() => loadConfig({ DKIM_BACKEND: "other" }), /DKIM_BACKEND/);
  assert.throws(
    () => loadConfig({ DKIM_BACKEND: "rspamd", DKIM_SELECTOR: "default" }),
    /Rspamd/,
  );
  for (const timeout of ["999", "60001"])
    assert.throws(
      () => loadConfig({ RSPAMD_TIMEOUT_MS: timeout }),
      /RSPAMD_TIMEOUT_MS/,
    );
});

test("Rspamd keys are generated by the CLI, published without replacement, and reused", async () => {
  const directory = await mkdtemp(
    path.join(os.tmpdir(), "postoffice-rspamd-key-"),
  );
  const config = {
    dkimBackend: "rspamd",
    rspamdKeyDir: directory,
    rspamdSelector: "rspamd20261019",
    rspamadmPath: "/usr/bin/rspamadm",
  };
  let calls = 0;
  const run = async (binary, args, options) => {
    calls++;
    assert.equal(binary, "/usr/bin/rspamadm");
    assert.deepEqual(args.slice(0, 7), [
      "dkim_keygen",
      "-b",
      "2048",
      "-s",
      "rspamd20261019",
      "-d",
      "sample.example",
    ]);
    assert.equal(args[7], "-k");
    assert.equal(path.dirname(path.dirname(args[8])), directory);
    assert.equal(options.timeout, 10000);
    assert.equal(options.windowsHide, true);
    await writeFile(args[8], (await fixture).privateKey, { mode: 0o600 });
  };
  try {
    const key = await generateDomainKey(config, "sample.example", { run });
    assert.equal(key.publicKey, (await fixture).publicKey);
    assert.equal(key.selector, "rspamd20261019");
    assert.deepEqual(
      await generateDomainKey(config, "sample.example", { run }),
      key,
    );
    assert.equal(calls, 1);
    assert.deepEqual(await readdir(directory), [
      "sample.example.rspamd20261019.key",
    ]);
    if (process.platform !== "win32")
      assert.equal(
        (await stat(rspamdKeyPath(config, "sample.example"))).mode & 0o777,
        0o640,
      );
    await assert.rejects(generateDomainKey(config, "../../invalid", { run }));
    await assert.rejects(
      generateDomainKey(
        { ...config, rspamdSelector: "../bad" },
        "sample.example",
        { run },
      ),
    );
    assert.equal(calls, 1);
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
});

test("Rspamd startup migrates once and restores a matching persisted private key", async () => {
  const directory = await mkdtemp(
    path.join(os.tmpdir(), "postoffice-rspamd-restore-"),
  );
  const config = { dkimBackend: "rspamd", rspamdKeyDir: directory };
  const db = database();
  const legacy = await generateDomainKey();
  db.prepare("INSERT INTO domain_keys VALUES(1,?,?,?)").run(
    legacy.selector,
    legacy.privateKey,
    legacy.publicKey,
  );
  let calls = 0;
  const run = async (_binary, args) => {
    calls++;
    await writeFile(args[8], (await fixture).privateKey, { mode: 0o600 });
  };
  try {
    await ensureDomainKeys(db, config, { run });
    const row = db.prepare("SELECT * FROM domain_keys WHERE domain_id=1").get();
    assert.equal(row.selector, "rspamd");
    assert.equal(row.public_key, (await fixture).publicKey);
    assert.notEqual(row.public_key, legacy.publicKey);
    await ensureDomainKeys(db, config, { run });
    assert.equal(calls, 1);
    const filename = rspamdKeyPath(config, "sample.example");
    await rm(filename);
    await ensureDomainKeys(db, config, { run });
    assert.equal(await readFile(filename, "utf8"), row.private_key);
    assert.equal(calls, 1);
    await writeFile(filename, legacy.privateKey);
    await assert.rejects(ensureDomainKeys(db, config, { run }), /数据库不匹配/);
    assert.equal(
      db.prepare("SELECT public_key FROM domain_keys WHERE domain_id=1").get()
        .public_key,
      row.public_key,
    );
  } finally {
    db.close();
    await rm(directory, { recursive: true, force: true });
  }
});

test("Rspamd CLI failure preserves the database and removes partial private material", async () => {
  const directory = await mkdtemp(
    path.join(os.tmpdir(), "postoffice-rspamd-fail-"),
  );
  const db = database();
  const config = { dkimBackend: "rspamd", rspamdKeyDir: directory };
  try {
    await assert.rejects(
      ensureDomainKeys(db, config, {
        run: async (_binary, args) => {
          await writeFile(args[8], "partial private secret");
          throw Object.assign(new Error("sensitive CLI output"), {
            stdout: "secret",
          });
        },
      }),
      (error) =>
        /Rspamd DKIM/.test(error.message) &&
        !/secret|sensitive/.test(error.message),
    );
    assert.equal(
      db.prepare("SELECT COUNT(*) AS n FROM domain_keys").get().n,
      0,
    );
    assert.deepEqual(await readdir(directory), []);
  } finally {
    db.close();
    await rm(directory, { recursive: true, force: true });
  }
});
