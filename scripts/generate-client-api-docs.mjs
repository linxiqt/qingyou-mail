// Bundle the reviewed server contract locally. The UI loads this only on demand.
import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const spec = JSON.parse(await readFile(new URL('docs/api/openapi.json', root), 'utf8'));
const mailSpec = JSON.parse(await readFile(new URL('docs/api/openapi-mail.json', root), 'utf8'));
const source = '// Generated by scripts/generate-client-api-docs.mjs; do not edit.\n'
  + `export const spec = ${JSON.stringify(spec)};\n`
  + `export const mailOperationIds = ${JSON.stringify(Object.values(mailSpec.paths).flatMap(path => Object.values(path).map(op => op.operationId)))};\n`;
const destination = new URL('clients/ui/api-reference-data.js', root);
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== source) throw Error('Client API reference is stale; run node scripts/generate-client-api-docs.mjs');
} else await writeFile(destination, source);
